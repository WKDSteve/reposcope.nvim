-- Live check: the core loop, search -> list -> README preview, section 1 (task reposcope.nvim/manual-checklist-run;
-- ALL/manual-test-checklists/reposcope.md). The request tools are a fake (TESTS/sheets/_helpers.lua): no network.
return {
  id = "reposcope.core-loop",
  title = "reposcope.nvim: a search fills the list, moving the selection previews that README, a count moves once",
  task = "reposcope.nvim/manual-checklist-run",
  sizes = { { rows = 40, cols = 140 } },
  steps = {
    { lua = [[dofile(vim.fn.getcwd() .. "/TESTS/sheets/_helpers.lua"); _G.setup({ readme_precache_count = 0 })]] },
    { keys = ":Reposcope start<CR>" },
    { wait = [[_G.rbuf("list") ~= nil and _G.field("keywords") ~= nil]], note = "the UI is open" },
    { wait = [[_G.in_field("keywords") and vim.fn.mode() == "i"]], note = "the prompt waits in insert mode" },
    { input = "spotlight" },
    { wait = [[_G.typed("keywords", "spotlight")]] },
    { input = "<Tab>" },
    { wait = [[_G.in_field("owner")]] },
    { input = "alice" },
    { wait = [[_G.typed("keywords", "spotlight") and _G.typed("owner", "alice")]] },
    { input = "<CR>", note = "search" },
    { wait = [[#_G.list() == #_G.fixture and _G.list()[1] ~= ""]], note = "the whole result set, no truncation" },
    { expect = [[_G.has(_G.list()[1], "alice/spotlight: Search everything fast")]] },
    { expect = [[_G.has(_G.requests[1], "spotlight") and _G.has(_G.requests[1], "alice")]] },
    { wait = [[_G.preview():find("README of alice/spotlight", 1, true) ~= nil]], note = "the first README" },
    { input = "<Down>", note = "insert mode: one entry" },
    { wait = [[_G.selected() == 2 and _G.preview():find("README of bob/lantern", 1, true) ~= nil]] },
    { input = "<Esc>" },
    { wait = [[vim.fn.mode() == "n"]] },
    { lua = [[_G.before = _G.asked("raw.githubusercontent.com")]] },
    { keys = "3<Down>", note = "a count in normal mode" },
    { wait = [[_G.selected() == 5 and _G.preview():find("README of dave/torch", 1, true) ~= nil]] },
    { lua = "vim.wait(400)" },
    {
      expect = [[_G.asked("raw.githubusercontent.com") - _G.before == 1]],
      note = "fetched once, for the entry it lands on",
    },
    { keys = "9<Down>" },
    { wait = [[_G.selected() == #_G.fixture]], note = "clamped at the end" },
    { keys = "99<Up>" },
    { wait = [[_G.selected() == 1]], note = "clamped at the start" },
  },
}
